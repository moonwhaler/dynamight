// Test double for the paraglide message functions (see vitest.config.ts).
// Each message returns its key, plus its parameters when called with some,
// e.g. `jobs_count({ count: 3 })` -> 'jobs_count(count=3)'.
// One export per key in messages/en.json; paraglideMock.test.ts checks this.

type Params = Record<string, unknown>;

const message =
  (key: string) =>
  (params?: Params): string => {
    if (params && typeof params === 'object') {
      const s = Object.entries(params)
        .map(([k, v]) => `${k}=${v}`)
        .join(',');
      return `${key}(${s})`;
    }
    return key;
  };

